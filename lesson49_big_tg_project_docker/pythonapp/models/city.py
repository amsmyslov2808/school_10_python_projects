"""Модель города, используемая API-, сервисным и UI-слоями."""

from dataclasses import dataclass


@dataclass
class City:
    """Хранит основные данные о городе, полученном из GeoNames.

    ``distance`` измеряется в километрах относительно исходного города.
    Для исходного города расстояние не передаётся и остаётся равным нулю.
    """

    # Название отображается пользователю в сообщениях Telegram.
    name: str
    # Широта и долгота нужны для последующего поиска соседних городов.
    latitude: float
    longitude: float
    # Значение по умолчанию удобно при создании исходного города по названию.
    distance: float = 0
