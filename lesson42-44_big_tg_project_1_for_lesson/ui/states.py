"""Состояния конечного автомата, описывающего навигацию по экранам бота."""

from telebot.states import State, StatesGroup


class TravelStates(StatesGroup):
    """Все возможные этапы диалога пользователя с TravelHunter.

    Состояние хранится отдельно для каждого пользователя/чата и помогает
    понять, какой обработчик должен принять следующее сообщение или нажатие.
    Номер в имени соответствует номеру экрана в сценарии приложения.
    """

    # Главное меню с выбором раздела.
    screen_2_main_menu = State()
    # Список праздников на ближайшие семь дней.
    screen_3_holidays = State()
    # Ожидание текстового сообщения с названием исходного города.
    screen_4_city_input = State()
    # Список городов, расположенных рядом с введённым городом.
    screen_5_nearby_cities = State()
    # Подробная информация о выбранном городе.
    screen_6_city_info = State()
    # История сохранённых пользователем поездок.
    screen_7_trips = State()
    # Подробности одной поездки из истории.
    screen_8_trip_info = State()
    # Ожидание пользовательской заметки о поездке.
    screen_9_note_input = State()
