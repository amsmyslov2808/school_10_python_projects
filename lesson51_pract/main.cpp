#include <iostream>

using namespace std;

int main() {
    // Начальный баланс и флаг, который управляет работой программы.
    int balance_money = 10000;
    bool is_run = true;

    // Показываем меню снова, пока пользователь не выберет выход.
    while (is_run) {
        // %d заменяется текущим целым значением переменной balance_money.
        printf("Текущий баланс на счету: %d руб.\n\n", balance_money);

        // Выводим список доступных пользователю действий.
        printf("Меню:\n");
        printf("1. Полнить баланс\n");
        printf("2. Снять деньги\n");
        printf("3. Разменять деньги на определённые купюры\n");
        printf("0. Выйти из программы\n");

        printf("Введите действие: ");
        int choose_action;

        // Считываем номер выбранного пункта и записываем его в choose_action.
        scanf("%d", &choose_action);

        // Выполняем действие, соответствующее выбранному пункту меню.
        switch (choose_action) {
            case 1: {
                // Первый пункт отвечает за пополнение счёта.
                printf("Введие сумму нужную для пополнения: ");
                int income_money;

                // Сохраняем введённую сумму пополнения.
                scanf("%d", &income_money);

                // При пополнении введённая сумма прибавляется к балансу.
                balance_money += income_money;
                printf("Баланс успешно пополнен");
            }
            break;
            case 2: {
                // Второй пункт отвечает за снятие денег со счёта.
                printf("Введие сумму нужную для снятия: ");
                int outcome_money;

                // Сохраняем сумму, которую пользователь хочет снять.
                scanf("%d", &outcome_money);

                // Нельзя снять больше денег, чем сейчас есть на счёте.
                if (outcome_money > balance_money) {
                    printf("Ошибка. Невозможно списать денег больше чем у вас есть на балансе.");
                } else {
                    // Если денег достаточно, вычитаем указанную сумму из баланса.
                    balance_money -= outcome_money;
                    printf("Баланс успешно уменьшен");
                }
            }
            break;
            case 3: {
                // Третий пункт рассчитывает количество купюр заданного номинала.
                printf("Введие сумму нужную для размена: ");
                int change_money;

                // В change_money хранится номинал одной купюры.
                scanf("%d", &change_money);

                // Остаток должен быть равен нулю, чтобы сумма делилась на купюры без остатка.
                if (balance_money%change_money!=0) {
                    printf("Ошибка. Невозможно разменять %d по %d руб.", balance_money, change_money);
                }else {
                    // Делим весь баланс на номинал и получаем количество купюр.
                    printf("Можно разменять я выдам вам %d купюр по %d рублей",balance_money/change_money, change_money);
                }
            }
            break;
            case 0: {
                // Меняем флаг, и после этой итерации цикл завершится.
                is_run = false;
                printf("Программа будет закрыта");
            }
            break;
            default: {
                // default срабатывает, если введённого номера нет в меню.
                printf("Ошибка. Такого действия нет");
            }
            break;
        }


        // Перед повторным показом меню даём пользователю прочитать результат.
        printf("\n\n\nНажмите Enter, чтобы продолжить...");
        getchar();     // Убираем символ Enter, оставшийся после scanf.
        getchar();     // Ждём новое нажатие Enter от пользователя.
        printf("\n-----------------------------------\n\n");
    }
}
